export function searchLocations(query = "") {
  const q = query
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
  return LOCATIONS.filter((p) =>
    `${p.name} ${p.country} ${p.id}`
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .includes(q),
  );
}
export function parseLocation(value) {
  const known = LOCATIONS.find(
    (p) => p.id === value || p.name.toLowerCase() === value.toLowerCase(),
  );
  if (known) return known;
  const parts = value
    .trim()
    .split(",")
    .map((v) => v.trim());
  if (
    parts.length !== 2 ||
    parts.some((v) => !/^[+-]?(?:\d+(?:\.\d*)?|\.\d+)$/.test(v))
  )
    return null;
  const [lat, lon] = parts.map(Number);
  if (lat < -90 || lat > 90 || lon < -180 || lon > 180) return null;
  return {
    id: `custom-${lat}-${lon}`,
    name: `${lat.toFixed(3)}°, ${lon.toFixed(3)}°`,
    country: "Custom coordinates",
    code: "XY",
    lat,
    lon,
  };
}
